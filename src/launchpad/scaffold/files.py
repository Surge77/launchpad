"""Glue files every scaffolded project gets, regardless of stack."""

from __future__ import annotations

from dataclasses import dataclass

from launchpad.scaffold.plan import FileSpec


@dataclass(frozen=True)
class TaskSpec:
    """A task to write into the generated launcher.toml."""

    name: str
    cmd: str
    subdir: str = ""
    port: int | None = None
    open_browser: bool = False


def launcher_toml(tasks: list[TaskSpec]) -> FileSpec:
    """The generated project is launchable with `launch up <name>` immediately."""
    blocks = ["# Generated by `launch new`. Edit freely — this file wins over auto-detection.\n"]
    for task in tasks:
        lines = [f'[[task]]\nname = "{task.name}"\ncmd  = "{task.cmd}"']
        if task.subdir:
            lines.append(f'cwd  = "{task.subdir}"')
        if task.port is not None:
            lines.append(f"port = {task.port}")
        if task.open_browser:
            lines.append("open = true")
        blocks.append("\n".join(lines))
    return FileSpec(path="launcher.toml", content="\n\n".join(blocks) + "\n")


def env_example(variables: dict[str, str]) -> FileSpec:
    body = "\n".join(f"{key}={value}" for key, value in variables.items())
    return FileSpec(path=".env.example", content=body + "\n")


def readme(name: str, stack_title: str, run_lines: list[str], notes: list[str]) -> FileSpec:
    steps = "\n".join(f"{index}. {line}" for index, line in enumerate(run_lines, start=1))
    extra = "\n".join(f"- {note}" for note in notes)
    content = f"""# {name}

{stack_title}, scaffolded with [launchpad](https://github.com/Surge77/launchpad).

## Run it

```sh
launch up {name}
```

That opens your editor and starts every process defined in `launcher.toml`.

## Run it manually

{steps}

## Notes

{extra}
"""
    return FileSpec(path="README.md", content=content)


def postgres_compose(service: str, port: int = 5432) -> FileSpec:
    content = f"""services:
  postgres:
    image: postgres:17-alpine
    container_name: {service}-postgres
    restart: unless-stopped
    environment:
      POSTGRES_USER: {service}
      POSTGRES_PASSWORD: {service}
      POSTGRES_DB: {service}
    ports:
      - "{port}:5432"
    volumes:
      - postgres-data:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U {service}"]
      interval: 5s
      retries: 10

volumes:
  postgres-data:
"""
    return FileSpec(path="docker-compose.yml", content=content)


def mongo_compose(service: str, port: int = 27017) -> FileSpec:
    content = f"""services:
  mongo:
    image: mongo:8
    container_name: {service}-mongo
    restart: unless-stopped
    ports:
      - "{port}:27017"
    volumes:
      - mongo-data:/data/db

volumes:
  mongo-data:
"""
    return FileSpec(path="docker-compose.yml", content=content)
